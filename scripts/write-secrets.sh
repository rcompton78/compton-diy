#!/usr/bin/env bash
# Generates <project-dir>/builds/secrets.yaml from builds/secrets.yaml.example,
# taking each key from a per-app environment variable (COM-463):
# <APP>_<UPPERCASED_KEY>, where APP is the project dir's name upper-cased with
# dashes turned into underscores. So apps/media-room-dashboard's
# `api_encryption_key` comes from $MEDIA_ROOM_DASHBOARD_API_ENCRYPTION_KEY.
# There's deliberately no shared fallback (no HA_<KEY> or bare <KEY>): a
# shared value is how release builds once baked a key into the remote that
# HA had never been given.
#
# A gitignored <project-dir>/.env (plain VAR=value lines) is sourced first,
# like scripts/pio.sh, and its values win over exported shell vars.
#
# Without the var, a key keeps the value of a secrets.yaml this script
# generated earlier, else the example's placeholder, with a warning, so PR
# builds still compile. REQUIRE_APP_SECRETS=1 (set by release.yml) makes a
# missing var fatal instead, so a release can't ship a placeholder key.
#
# A secrets.yaml without the generated marker below is a developer's own
# hand-written file: it's left untouched, never overwritten.
#
# Only key and variable names are printed, never values.
#
# Usage: scripts/write-secrets.sh <project-dir>
set -euo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT_DIR="$REPO_ROOT/${1:?usage: $0 <project-dir>}"
DIR="$PROJECT_DIR/builds"
EXAMPLE="$DIR/secrets.yaml.example"
OUT="$DIR/secrets.yaml"
MARKER="# Generated by scripts/write-secrets.sh from secrets.yaml.example. Delete to regenerate."
APP_PREFIX="$(basename "$PROJECT_DIR" | tr '[:lower:]-' '[:upper:]_')"
STRICT="${REQUIRE_APP_SECRETS:-}"

if [ ! -f "$EXAMPLE" ]; then
    echo "==> $EXAMPLE not found" >&2
    exit 1
fi

if [ -f "$PROJECT_DIR/.env" ]; then
    set -a
    # shellcheck disable=SC1091
    . "$PROJECT_DIR/.env"
    set +a
fi

declare -A previous=()
if [ -f "$OUT" ]; then
    if [ "$(head -n 1 "$OUT")" != "$MARKER" ]; then
        echo "==> $OUT isn't generated by this script, leaving it as-is"
        exit 0
    fi
    while IFS= read -r line; do
        if [[ "$line" =~ ^([A-Za-z0-9_]+): ]]; then
            previous["${BASH_REMATCH[1]}"]="$line"
        fi
    done < "$OUT"
fi

echo "==> Generating $OUT"
TMP="$OUT.tmp"
trap 'rm -f "$TMP"' EXIT
umask 077
echo "$MARKER" > "$TMP"
missing=()
while IFS= read -r line; do
    if [[ "$line" =~ ^([A-Za-z0-9_]+):.*$ ]]; then
        key="${BASH_REMATCH[1]}"
        env_name="${APP_PREFIX}_$(echo "$key" | tr '[:lower:]' '[:upper:]')"
        env_value="${!env_name:-}"
        if [ -n "$env_value" ]; then
            escaped="$(printf '%s' "$env_value" | sed 's/\\/\\\\/g; s/"/\\"/g; s/\t/\\t/g' | sed ':a;N;$!ba;s/\n/\\n/g')"
            printf '%s: "%s"\n' "$key" "$escaped" >> "$TMP"
            echo "    $key: from \$$env_name"
            continue
        fi
        if [ -n "$STRICT" ]; then
            missing+=("$env_name")
        elif [ -n "${previous[$key]:-}" ] && [ "${previous[$key]}" != "$line" ]; then
            echo "${previous[$key]}" >> "$TMP"
            echo "    $key: \$$env_name not set, keeping the previously generated value"
            continue
        else
            echo "    WARNING: $key: \$$env_name not set, using the example's placeholder" >&2
        fi
    fi
    echo "$line" >> "$TMP"
done < "$EXAMPLE"

if [ "${#missing[@]}" -gt 0 ]; then
    echo "==> REQUIRE_APP_SECRETS is set but these aren't: ${missing[*]}" >&2
    echo "    Add each as a GitHub Actions repo secret and pass it in release.yml's env." >&2
    exit 1
fi

if [ -f "$OUT" ] && cmp -s "$TMP" "$OUT"; then
    rm -f "$TMP"
else
    mv "$TMP" "$OUT"
fi
trap - EXIT
